/// Offsets into the mhbd header (`MhbdHeader` in libgpod's db-itunes-parser.h).
const DB_ID_AT: usize = 0x18;
const HASHING_SCHEME_AT: usize = 0x30;
const UNKNOWN_AT: usize = 0x32;
const UNKNOWN_LEN: usize = 20;
const HASH_AT: usize = 0x58;
const HASH_LEN: usize = 20;
/// libgpod refuses files too short to hold the hash field.
const MIN_LEN: usize = 0x6c;
/// `ITDB_CHECKSUM_HASH58`, which the header records so the iPod knows how to verify the file.
const SCHEME_HASH58: u16 = 1;

fn gcd(mut a: u32, mut b: u32) -> u32 {
    while b != 0 {
        (a, b) = (b, a % b);
    }
    a
}

fn lcm(a: u32, b: u32) -> u32 {
    if a == 0 || b == 0 {
        1
    } else {
        a * b / gcd(a, b)
    }
}

/// SHA-1 of a fixed string and four substitution-table lookups per pair of GUID bytes, padded with
/// zeros to the 64-byte HMAC block.
fn key(firewire_id: &[u8; 8]) -> [u8; 64] {
    let mut scrambled = [0u8; 16];
    for (pair, out) in firewire_id
        .chunks_exact(2)
        .zip(scrambled.chunks_exact_mut(4))
    {
        let lcm = lcm(u32::from(pair[0]), u32::from(pair[1]));
        let (high, low) = (usize::from((lcm >> 8) as u8), usize::from(lcm as u8));
        out.copy_from_slice(&[TABLE1[high], TABLE2[high], TABLE1[low], TABLE2[low]]);
    }
    let mut sha = Sha1::new();
    sha.update(FIXED);
    sha.update(scrambled);
    let mut key = [0u8; 64];
    key[..20].copy_from_slice(&sha.finalize());
    key
}

/// HMAC-SHA1, spelled out the way libgpod does.
fn hash(firewire_id: &[u8; 8], data: &[u8]) -> [u8; 20] {
    let mut key = key(firewire_id);
    key.iter_mut().for_each(|byte| *byte ^= 0x36);
    let mut inner = Sha1::new();
    inner.update(key);
    inner.update(data);
    let inner = inner.finalize();

    key.iter_mut().for_each(|byte| *byte ^= 0x36 ^ 0x5c);
    let mut outer = Sha1::new();
    outer.update(key);
    outer.update(inner);
    outer.finalize().into()
}

/// Writes the checksum into the finished database `file`. The database id, an unknown 20-byte field
/// and the hash field itself are zero while hashing and restored afterwards, as in libgpod's
/// `itdb_hash58_write_hash`.
pub(crate) fn seal(file: &mut [u8], firewire_id: &[u8; 8]) -> Result<()> {
    if file.len() < MIN_LEN || file.get(..4) != Some(b"mhbd") {
        return Err(Error::corrupt(0, "database too short to hold a checksum"));
    }
    let db_id = file[DB_ID_AT..DB_ID_AT + 8].to_vec();
    let unknown = file[UNKNOWN_AT..UNKNOWN_AT + UNKNOWN_LEN].to_vec();
    put(file, DB_ID_AT, &[0; 8]);
    put(file, UNKNOWN_AT, &[0; UNKNOWN_LEN]);
    put(file, HASH_AT, &[0; HASH_LEN]);
    put(file, HASHING_SCHEME_AT, &SCHEME_HASH58.to_le_bytes());

    let checksum = hash(firewire_id, file);

    put(file, DB_ID_AT, &db_id);
    put(file, UNKNOWN_AT, &unknown);
    put(file, HASH_AT, &checksum);
    Ok(())
}

/// Whether the checksum stored in `file` is the one this device's GUID produces, i.e. whether a
/// database written by iTunes passes the same check the iPod applies. `None` if the file is too
/// short to hold one.
pub(crate) fn verify(file: &[u8], firewire_id: &[u8; 8]) -> Option<bool> {
    let stored = file.get(HASH_AT..HASH_AT + HASH_LEN)?.to_vec();
    let mut zeroed = file.to_vec();
    put(&mut zeroed, DB_ID_AT, &[0; 8]);
    put(&mut zeroed, UNKNOWN_AT, &[0; UNKNOWN_LEN]);
    put(&mut zeroed, HASH_AT, &[0; HASH_LEN]);
    Some(hash(firewire_id, &zeroed)[..] == stored[..])
}

/// The hashing scheme recorded in the mhbd header (0 none, 1 HASH58, 2 HASH72, 3 HASHAB).
pub(crate) fn scheme(file: &[u8]) -> Option<u16> {
    crate::bytes::u16_at(file, HASHING_SCHEME_AT)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Computed by libgpod's own algorithm, compiled from itdb_hash58.c with CommonCrypto SHA-1
    /// standing in for GChecksum, over `data[i] = (i * 7 + 3) % 256`.
    fn vector(firewire_id: [u8; 8], len: usize, expected: &str) {
        let data: Vec<u8> = (0..len).map(|i| ((i * 7 + 3) % 256) as u8).collect();

        let actual = hash(&firewire_id, &data);

        let hex: String = actual.iter().map(|byte| format!("{byte:02x}")).collect();
        assert_eq!(hex, expected);
    }

    #[test]
    fn matches_libgpod_for_a_typical_guid() {
        vector(
            [0x00, 0x0a, 0x27, 0x00, 0x1a, 0x2b, 0x3c, 0x4d],
            300,
            "4ebcc8f948a1a233acde476f674e4fa08a591358",
        );
    }

    #[test]
    fn matches_libgpod_when_a_pair_of_guid_bytes_is_zero() {
        vector(
            [0x00, 0x00, 0x00, 0x00, 0x12, 0x34, 0x56, 0x78],
            64,
            "c542ac17d1526ee534188657a8fbb6083d611e60",
        );
    }

    #[test]
    fn matches_libgpod_when_the_lcm_needs_both_bytes() {
        vector(
            [0xff, 0xfe, 0xfd, 0xfc, 0xfb, 0xfa, 0xf9, 0xf8],
            1000,
            "ebc4de47951e4a38270b31ee09142f00bd80f39c",
        );
    }

    #[test]
    fn matches_libgpod_for_empty_data() {
        vector(
            [0x00, 0x0a, 0x27, 0x00, 0x1a, 0x2b, 0x3c, 0x4d],
            0,
            "4dbcc86bb2bca26b060c1bdc49410bd3191be514",
        );
    }

    #[test]
    fn sealing_hashes_with_the_volatile_fields_zeroed_and_restores_them() {
        let id = [0x00, 0x0a, 0x27, 0x00, 0x1a, 0x2b, 0x3c, 0x4d];
        let mut file = vec![0xaa; 300];
        file[..4].copy_from_slice(b"mhbd");

        seal(&mut file, &id).unwrap();

        let mut zeroed = vec![0xaa; 300];
        zeroed[..4].copy_from_slice(b"mhbd");
        zeroed[DB_ID_AT..DB_ID_AT + 8].fill(0);
        zeroed[UNKNOWN_AT..UNKNOWN_AT + UNKNOWN_LEN].fill(0);
        zeroed[HASH_AT..HASH_AT + HASH_LEN].fill(0);
        zeroed[HASHING_SCHEME_AT..HASHING_SCHEME_AT + 2].copy_from_slice(&[1, 0]);
        assert_eq!(&file[HASH_AT..HASH_AT + HASH_LEN], hash(&id, &zeroed));
        assert_eq!(&file[DB_ID_AT..DB_ID_AT + 8], &[0xaa; 8]);
        assert_eq!(
            &file[UNKNOWN_AT..UNKNOWN_AT + UNKNOWN_LEN],
            &[0xaa; UNKNOWN_LEN]
        );
        assert_eq!(&file[HASHING_SCHEME_AT..HASHING_SCHEME_AT + 2], &[1, 0]);
    }

    #[test]
    fn a_sealed_file_verifies_and_a_damaged_one_does_not() {
        let id = [0x00, 0x0a, 0x27, 0x00, 0x1a, 0x2b, 0x3c, 0x4d];
        let mut file = vec![0x55; 300];
        file[..4].copy_from_slice(b"mhbd");
        seal(&mut file, &id).unwrap();

        assert_eq!(verify(&file, &id), Some(true));
        assert_eq!(
            verify(&file, &[1; 8]),
            Some(false),
            "another iPod's GUID does not verify"
        );
        file[200] ^= 1;
        assert_eq!(verify(&file, &id), Some(false));
        assert_eq!(verify(&file[..0x40], &id), None);
    }

    #[test]
    fn a_file_too_short_for_the_hash_is_refused() {
        let mut file = b"mhbd".to_vec();
        file.resize(0x40, 0);

        assert!(seal(&mut file, &[0; 8]).is_err());
    }
}
