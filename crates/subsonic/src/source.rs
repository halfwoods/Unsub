use std::{io::Read, path::PathBuf};

use crate::{
    Result,
    model::{Album, Artist, Genre, Playlist, SearchResult, Song},
};

/// Orderings for [`MusicSource::album_list`]. Subsonic's `starred` and `highest` lists are always
/// empty here and never reach the source.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AlbumListKind {
    Random,
    Newest,
    Frequent,
    Recent,
    AlphabeticalByName,
    AlphabeticalByArtist,
    ByYear,
    ByGenre,
}

/// A format a client can ask `stream` to convert to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StreamFormat {
    Mp3,
    /// AAC-LC, as ADTS when streamed.
    Aac,
    Opus,
    Flac,
}

impl StreamFormat {
    pub fn name(self) -> &'static str {
        match self {
            Self::Mp3 => "mp3",
            Self::Aac => "aac",
            Self::Opus => "opus",
            Self::Flac => "flac",
        }
    }
}

/// Audio to send to a client.
pub enum Stream {
    /// A file on disk; the server handles `Range` requests itself.
    File { path: PathBuf, content_type: String },
    /// Generated bytes, such as a transcode. Not seekable, so `Range` is ignored.
    Reader {
        reader: Box<dyn Read + Send>,
        content_type: String,
        length: Option<u64>,
    },
}

/// Everything the server needs from the host application.
///
/// Calls arrive on a blocking thread pool, so implementations may block on a database or on disk.
/// Ids are opaque to the crate. `Ok(None)` means "no such id" and becomes Subsonic error 70.
pub trait MusicSource: Send + Sync + 'static {
    fn artists(&self) -> Result<Vec<Artist>>;
    fn artist(&self, id: &str) -> Result<Option<(Artist, Vec<Album>)>>;
    fn album(&self, id: &str) -> Result<Option<(Album, Vec<Song>)>>;
    fn song(&self, id: &str) -> Result<Option<Song>>;

    /// `genre` is set only for [`AlbumListKind::ByGenre`] and `years` only for
    /// [`AlbumListKind::ByYear`]. For `ByYear` the range is inclusive and `from > to` asks for the
    /// newest albums first.
    fn album_list(
        &self,
        kind: AlbumListKind,
        size: usize,
        offset: usize,
        genre: Option<&str>,
        years: Option<(i32, i32)>,
    ) -> Result<Vec<Album>>;

    /// `years` is an inclusive range with `from <= to`.
    fn random_songs(
        &self,
        size: usize,
        genre: Option<&str>,
        years: Option<(i32, i32)>,
    ) -> Result<Vec<Song>>;

    /// Each kind is `(count, offset)`. An empty `query` means "everything": clients that sync the
    /// whole library page through `search3` with an empty query.
    fn search(
        &self,
        query: &str,
        artists: (usize, usize),
        albums: (usize, usize),
        songs: (usize, usize),
    ) -> Result<SearchResult>;

    fn genres(&self) -> Result<Vec<Genre>>;
    fn playlists(&self) -> Result<Vec<Playlist>>;
    fn playlist(&self, id: &str) -> Result<Option<(Playlist, Vec<Song>)>>;

    /// Returns `(mime type, image bytes)`, scaled to fit `size` pixels when given.
    fn cover_art(&self, id: &str, size: Option<u32>) -> Result<Option<(String, Vec<u8>)>>;

    /// The song exactly as stored. This is what `download` sends and what `stream` sends when no
    /// conversion is wanted or [`MusicSource::transcoded`] does not do one.
    fn open_stream(&self, song_id: &str) -> Result<Option<Stream>>;

    /// The song converted to `format`, for a client that asked for it (`format`) or for a lower
    /// bitrate (`max_kbps`), or because the server's default cap applies. It is only called when the
    /// song needs converting: the format differs, or its bitrate exceeds `max_kbps`. `max_kbps` is
    /// `None` when no cap applies, and lossless targets ignore it.
    ///
    /// Returns the converted bytes and their content type. They are sent chunked, without a length
    /// and without `Range` support. `None` means this source cannot convert, and the original is
    /// sent instead. `Some(Err(_))` is a failure and is reported to the client; answer `None` for
    /// "cannot" so playback still works.
    fn transcoded(
        &self,
        song_id: &str,
        format: StreamFormat,
        max_kbps: Option<u32>,
    ) -> Option<Result<(Box<dyn Read + Send>, &'static str)>> {
        let _ = (song_id, format, max_kbps);
        None
    }

    /// The client played the song. `time_ms` is when, in milliseconds since the Unix epoch, as the
    /// client reported it (the current time if it did not).
    fn scrobble(&self, song_id: &str, time_ms: i64) -> Result<()> {
        let _ = (song_id, time_ms);
        Ok(())
    }

    /// The client has started playing the song. `client` is the name it gave (`c`).
    fn now_playing(&self, song_id: &str, client: &str) -> Result<()> {
        let _ = (song_id, client);
        Ok(())
    }
}
